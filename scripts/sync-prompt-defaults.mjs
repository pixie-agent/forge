/**
 * 把 agent/orchestration/prompts/ 下的默认提示词树(shared/system/user 的 .md)生成为
 * src/lib/prompt-defaults.ts(路径 → 内容 的常量表),供 Worker 侧「下载当前提示词」
 * 组装有效树(默认 ⊕ 自定义覆盖)时用。单一事实源仍是 agent/orchestration/prompts/,
 * 这里只是构建时快照,由 build/check/deploy 自动重生成,勿手改生成产物。
 */
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const promptDir = join(root, 'agent', 'orchestration', 'prompts')
const outFile = join(root, 'src', 'lib', 'prompt-defaults.ts')

async function walk(dir, rel = '') {
  const out = {}
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const r = rel ? `${rel}/${e.name}` : e.name
    if (e.isDirectory()) Object.assign(out, await walk(join(dir, e.name), r))
    else if (e.isFile() && e.name.endsWith('.md')) out[r] = await readFile(join(dir, e.name), 'utf8')
  }
  return out
}

const files = await walk(promptDir)
const entries = Object.entries(files).sort(([a], [b]) => a.localeCompare(b))
const body = entries.map(([p, c]) => `  ${JSON.stringify(p)}: ${JSON.stringify(c)}`).join(',\n')

await writeFile(
  outFile,
  '// AUTO-GENERATED by scripts/sync-prompt-defaults.mjs — do not edit by hand.\n' +
    '// Source of truth: agent/orchestration/prompts/*.md; regenerated on every build/check/deploy.\n' +
    '// 默认提示词树的构建时快照,供 /api/admin/prompts/download 组装「默认 ⊕ 自定义覆盖」的有效树。\n' +
    `export const DEFAULT_PROMPT_FILES: Record<string, string> = {\n${body},\n}\n`,
  'utf8',
)
console.log(`[sync-prompt-defaults] wrote ${entries.length} prompt files → ${relative(root, outFile)}`)
